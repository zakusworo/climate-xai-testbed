"""Write RESULTS.md from results/metrics.csv and results/global_importance.json."""

import json
from pathlib import Path

import pandas as pd
from scipy.stats import spearmanr

from climxai.xai import CAUSAL

ROOT = Path(__file__).resolve().parents[1]
m = pd.read_csv(ROOT / "results" / "metrics.csv")
gi = json.loads((ROOT / "results" / "global_importance.json").read_text())

# Spearman over causal features only: the proxies' true importance is tied at zero,
# so their mutual ordering is arbitrary and would depress an all-feature rho.
causal_rho = []
for g in gi:
    feats = [c for c in CAUSAL if c in g["model_global"]]
    causal_rho.append(spearmanr([g["model_global"][c] for c in feats], [g["true_global"][c] for c in feats]).statistic)
m["causal_spearman"] = causal_rho
m.to_csv(ROOT / "results" / "metrics_with_causal_rho.csv", index=False)

cols = ["case", "model", "seed", "noise", "r2", "rmse_mm", "causal_spearman", "global_spearman",
        "local_top1_match", "local_cosine_median", "spurious_share", "perm_spearman"]
t = m[cols].round(3)
e6 = m[m.case == "E6_bootstrap"]
e3 = m[m.case == "E3_no_rs"].set_index("model")
absorb = e3[[c for c in m if c.startswith("corr_rs_to_")]].T.round(2)
absorb.index = [i.replace("corr_rs_to_", "") for i in absorb.index]

md = ["# Results", "",
      "Generated by `scripts/make_results.py` from `results/metrics.csv` "
      f"({len(m)} runs; settings in `results/run_meta.json`). Do not edit by hand.", "",
      "`causal_spearman`: rank agreement over the 8 causal inputs. `global_spearman`: over all "
      "model features, including proxies whose true importance is tied at 0. `local_top1_match`: "
      "share of the 200 explained days where the model's largest |SHAP| feature equals the truth's. "
      "`spurious_share`: attribution on features FAO-56 never reads.", "",
      t.to_markdown(index=False), "",
      "## E6 bootstrap spread (HGB, 5 refits)", "",
      f"- local top-1 match: {e6.local_top1_match.min():.3f}–{e6.local_top1_match.max():.3f}",
      f"- causal Spearman: {e6.causal_spearman.min():.3f}–{e6.causal_spearman.max():.3f}",
      f"- spurious share: {e6.spurious_share.min():.3f}–{e6.spurious_share.max():.3f}", "",
      "## E3: where does the missing solar-radiation effect go?", "",
      f"Solar radiation carries {e3.dropped_true_share.iloc[0]:.0%} of the true total attribution. "
      "Correlation between its true per-day SHAP and each visible feature's model SHAP:", "",
      absorb.to_markdown(), ""]
(ROOT / "RESULTS.md").write_text("\n".join(md))
print("\n".join(md[:0]) or "RESULTS.md written")
